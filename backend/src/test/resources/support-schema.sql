CREATE TABLE mall_support_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, sender_id BIGINT NOT NULL, sender_role VARCHAR(16) NOT NULL,
 sender_name VARCHAR(255) NOT NULL, client_id VARCHAR(36) NOT NULL, content VARCHAR(2000) NOT NULL,
 creator VARCHAR(255), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(255), update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, deleted INTEGER DEFAULT 0,
 UNIQUE(user_id, sender_role, sender_id, client_id)
);
CREATE INDEX idx_support_message_user_id ON mall_support_message(user_id, id);
CREATE TABLE mall_chat_room (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 type VARCHAR(16) NOT NULL, title VARCHAR(80) NOT NULL,
 owner_role VARCHAR(16) NOT NULL, owner_id BIGINT NOT NULL,
 direct_key VARCHAR(128) UNIQUE, last_message_id BIGINT NOT NULL DEFAULT 0, last_content VARCHAR(2000) NOT NULL DEFAULT '',
 creator VARCHAR(255), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(255), update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, deleted INTEGER DEFAULT 0
);
CREATE TABLE mall_chat_member (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id BIGINT NOT NULL REFERENCES mall_chat_room(id), role VARCHAR(16) NOT NULL,
 account_id BIGINT NOT NULL, name VARCHAR(255) NOT NULL,
 creator VARCHAR(255), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(255), update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, deleted INTEGER DEFAULT 0,
 UNIQUE(room_id, role, account_id)
);
CREATE INDEX idx_chat_member_account ON mall_chat_member(role, account_id, room_id);
CREATE TABLE mall_chat_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id BIGINT NOT NULL REFERENCES mall_chat_room(id), sender_role VARCHAR(16) NOT NULL,
 sender_id BIGINT NOT NULL, sender_name VARCHAR(255) NOT NULL,
 client_id VARCHAR(36) NOT NULL, content VARCHAR(2000) NOT NULL,
 creator VARCHAR(255), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(255), update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, deleted INTEGER DEFAULT 0,
 UNIQUE(room_id, sender_role, sender_id, client_id)
);
CREATE INDEX idx_chat_message_room ON mall_chat_message(room_id, id);
